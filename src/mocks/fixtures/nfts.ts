import type { Edition, Image, NftDetail } from '@/contracts'

// `available` do NFT é derivado das edições na leitura; `status` não sai na API.
export type NftFixture = Omit<NftDetail, 'available' | 'image' | 'version'> & { status: 'active' | 'burned' }

// As imagens ficam em public/nfts/<id>-<n>.webp; a primeira é a capa do card.
function gallery(id: string, alts: string[]): Image[] {
  return alts.map((alt, index) => ({ src: `/nfts/${id}-${index + 1}.webp`, alt }))
}

function edition(id: string, name: string, media: string, supply: number, available: number): Edition {
  return { id, name, media, supply, available }
}

